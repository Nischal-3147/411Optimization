# 7. Virtual Sensor Sampling, Event Detection & Layout Scoring
# =============================================================================
def sample_virtual_sensors(
    P_32: np.ndarray,
    W: np.ndarray,
    sensor_xy: np.ndarray,
    gx: np.ndarray,
    gy: np.ndarray,
) -> np.ndarray:
    """Summed (T,) virtual-insole signal of N continuous sensors."""
    return sample_virtual_sensor_matrix(P_32, W, sensor_xy, gx, gy).sum(axis=1)


def sample_virtual_sensor_matrix(
    P_32: np.ndarray,
    W: np.ndarray,
    sensor_xy: np.ndarray,
    gx: np.ndarray,
    gy: np.ndarray,
) -> np.ndarray:
    """
    Bilinearly interpolate the (NY, NX, 32) weight grid at N continuous sensor
    positions, apply them to the raw (T, 32) pressures, and return the per-sensor
    (T, N) virtual pressures (each clipped at 0).
    """
    ny, nx = W.shape[0], W.shape[1]
    dx = gx[1] - gx[0]
    dy = gy[1] - gy[0]

    ix = np.clip((sensor_xy[:, 0] - gx[0]) / dx, 0.0, nx - 1.0001)
    iy = np.clip((sensor_xy[:, 1] - gy[0]) / dy, 0.0, ny - 1.0001)

    x0 = ix.astype(np.int32)
    y0 = iy.astype(np.int32)
    wx = (ix - x0).astype(np.float32)[:, None]
    wy = (iy - y0).astype(np.float32)[:, None]

    w_sensors = (                                       # (N, 32)
        (1.0 - wy) * (1.0 - wx) * W[y0, x0]
        + (1.0 - wy) * wx * W[y0, x0 + 1]
        + wy * (1.0 - wx) * W[y0 + 1, x0]
        + wy * wx * W[y0 + 1, x0 + 1]
    )
    return np.maximum(P_32 @ w_sensors.T, 0.0)


def contact_signal(
    P_32: np.ndarray,
    W: np.ndarray,
    sensor_xy: np.ndarray,
    gx: np.ndarray,
    gy: np.ndarray,
    aggregation: str = DEFAULT_AGGREGATION,
) -> Tuple[np.ndarray, Optional[float]]:
    """
    Combine N virtual sensors into one (T,) contact signal for HS/TO detection.
    Returns (signal, absolute_threshold); threshold None = detect_hs_to's default.

      "sum":        signal = sum of pressures; threshold = 10% of its p5–p95 range.
      "first_last": each sensor minus its own resting level (p5), divided by the
                    strongest sensor's p5–p95 range; signal = max over sensors,
                    threshold = FIRST_LAST_THRESH_FRAC. The max rises past the
                    threshold when the FIRST sensor loads and falls below it when
                    the LAST sensor unloads.
    """
    S = sample_virtual_sensor_matrix(P_32, W, sensor_xy, gx, gy)
    if aggregation == "sum":
        return S.sum(axis=1), None
    if aggregation != "first_last":
        raise ValueError(f"Unknown aggregation '{aggregation}'; choose from {AGGREGATIONS}.")

    lo = np.percentile(S, 5, axis=0)
    rng = np.percentile(S, 95, axis=0) - lo
    scale = float(rng.max())
    if scale < 1e-3:
        return np.zeros(len(S)), FIRST_LAST_THRESH_FRAC
    # Common scale (strongest sensor's range) so a weak, never-unloaded sensor's
    # noise cannot hold the foot "in contact" through swing.
    norm = (S - lo) / scale
    return norm.max(axis=1), FIRST_LAST_THRESH_FRAC


def detect_hs_to(
    t: np.ndarray,
    signal: np.ndarray,
    thresh_frac: float = THRESH_FRAC,
    min_phase_sec: float = MIN_PHASE_SEC,
    thresh_abs: Optional[float] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Detect heel-strike (rising) and toe-off (falling) times with sub-sample
    interpolation. Threshold = lo + thresh_frac·(hi − lo) of the signal's p5–p95
    range, unless an absolute `thresh_abs` is given.
    """
    lo = float(np.percentile(signal, 5))
    hi = float(np.percentile(signal, 95))
    if hi - lo < 1e-3:
        return np.empty(0), np.empty(0)

    thresh = thresh_abs if thresh_abs is not None else lo + thresh_frac * (hi - lo)
    state = signal >= thresh

    # Debounce brief threshold chatter (< min_phase_sec)
    min_samples = max(1, int(round(min_phase_sec * FS_HZ)))
    changed = True
    while changed:
        changed = False
        edges = np.where(np.diff(state.astype(np.int8)) != 0)[0] + 1
        for s, e in zip(np.r_[0, edges], np.r_[edges, len(state)]):
            if (e - s) < min_samples and s > 0 and e < len(state):
                state[s:e] = not state[s]
                changed = True
                break

    diffs = np.diff(state.astype(np.int8))
    hs_idx = np.where(diffs == 1)[0]
    to_idx = np.where(diffs == -1)[0]

    def _interp_crossings(idxs: np.ndarray) -> np.ndarray:
        if len(idxs) == 0:
            return np.empty(0, dtype=np.float64)
        y0 = signal[idxs]
        y1 = signal[idxs + 1]
        denom = np.where(y1 != y0, y1 - y0, 1.0)
        frac = np.clip((thresh - y0) / denom, 0.0, 1.0)
        return t[idxs] + frac * (t[idxs + 1] - t[idxs])

    return _interp_crossings(hs_idx), _interp_crossings(to_idx)


def _match_nearest(
    true_time: float,
    est_times: np.ndarray,
    max_window: float = MATCH_WINDOW_SEC,
    miss_penalty: float = MISS_PENALTY_SEC,
) -> Tuple[float, float]:
    """Match a single GAITRite event to its nearest detected crossing within max_window."""
    if len(est_times) == 0:
        return np.nan, miss_penalty
    idx = int(np.argmin(np.abs(est_times - true_time)))
    err = float(est_times[idx] - true_time)
    if abs(err) <= max_window:
        return float(est_times[idx]), err
    return np.nan, miss_penalty


def overlap_penalty(
    sensor_xy: np.ndarray,
    sensor_radius_cm: float = SENSOR_RADIUS_CM,
    penalty_weight: float = OVERLAP_LAMBDA,
) -> float:
    """
    Smooth quadratic exterior penalty enforcing non-overlap:
        (2r)^2 - [(x_a - x_b)^2 + (y_a - y_b)^2] < 0   for 1 <= a < b <= N
    """
    n = len(sensor_xy)
    if n < 2:
        return 0.0
    diff = sensor_xy[:, None, :] - sensor_xy[None, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    iu = np.triu_indices(n, k=1)
    violations = np.maximum(0.0, (2.0 * sensor_radius_cm) ** 2 - dist_sq[iu])
    return float(penalty_weight * np.sum(violations ** 2))


def check_constraints(
    sensor_xy: np.ndarray,
    width_cm: float = INSOLE_WIDTH_CM,
    length_cm: float = INSOLE_LENGTH_CM,
    sensor_radius_cm: float = SENSOR_RADIUS_CM,
) -> Dict[str, float | bool]:
    """Verify all mathematical programming constraints on a final sensor layout."""
    xy = np.asarray(sensor_xy, dtype=np.float64).reshape(-1, 2)
    n = len(xy)
    r = sensor_radius_cm

    in_bounds = bool(
        np.all(xy[:, 0] >= r - 1e-9)
        and np.all(xy[:, 0] <= width_cm - r + 1e-9)
        and np.all(xy[:, 1] >= r - 1e-9)
        and np.all(xy[:, 1] <= length_cm - r + 1e-9)
    )
    if n >= 2:
        diff = xy[:, None, :] - xy[None, :, :]
        dmat = np.linalg.norm(diff, axis=-1)
        np.fill_diagonal(dmat, np.inf)
        min_dist = float(dmat.min())
    else:
        min_dist = float("inf")

    no_overlap = bool(min_dist >= 2.0 * r - 1e-9)
    valid_n = bool(N_MIN <= n <= N_MAX)
    return {
        "feasible": valid_n and in_bounds and no_overlap,
        "valid_N": valid_n,
        "in_bounds": in_bounds,
        "no_overlap": no_overlap,
        "min_center_dist_cm": min_dist,
    }


def score_trial(
    sensor_xy: np.ndarray,
    trial: TrialData,
    dataset: InsoleDataset,
    aggregation: str = DEFAULT_AGGREGATION,
) -> Dict[str, float]:
    """Compute HS, TO, Step, Stride RMSEs and combined E(X) (ms) for one trial."""
    gx, gy = dataset.gx, dataset.gy
    sig_L, th_L = contact_signal(trial.raw_left, dataset.W_left, sensor_xy, gx, gy, aggregation)
    sig_R, th_R = contact_signal(trial.raw_right, dataset.W_right, sensor_xy, gx, gy, aggregation)

    hs_L, to_L = detect_hs_to(trial.t_left, sig_L, thresh_abs=th_L)
    hs_R, to_R = detect_hs_to(trial.t_right, sig_R, thresh_abs=th_R)

    gt = trial.ground_truth
    m = len(gt.foot)
    est_hs = np.full(m, np.nan, dtype=np.float64)
    hs_errs, to_errs, step_errs, stride_errs = [], [], [], []

    for i in range(m):
        h_pool, t_pool = (hs_L, to_L) if gt.foot[i] == 0 else (hs_R, to_R)
        m_hs, e_hs = _match_nearest(gt.first_contact[i], h_pool)
        _, e_to = _match_nearest(gt.last_contact[i], t_pool)
        est_hs[i] = m_hs
        hs_errs.append(e_hs)
        to_errs.append(e_to)

        if i >= 1 and gt.step_time[i] > 0:
            est_step = est_hs[i] - est_hs[i - 1]
            step_errs.append(
                (est_step - gt.step_time[i]) if np.isfinite(est_step) else MISS_PENALTY_SEC
            )
        if i >= 2 and gt.stride_time[i] > 0:
            est_stride = est_hs[i] - est_hs[i - 2]
            stride_errs.append(
                (est_stride - gt.stride_time[i]) if np.isfinite(est_stride) else MISS_PENALTY_SEC
            )

    rmse_hs = float(np.sqrt(np.mean(np.square(hs_errs)))) * 1000.0
    rmse_to = float(np.sqrt(np.mean(np.square(to_errs)))) * 1000.0
    rmse_step = float(np.sqrt(np.mean(np.square(step_errs)))) * 1000.0 if step_errs else 0.0
    rmse_stride = float(np.sqrt(np.mean(np.square(stride_errs)))) * 1000.0 if stride_errs else 0.0
    e_total = float(np.sqrt(0.25 * (rmse_hs**2 + rmse_to**2 + rmse_step**2 + rmse_stride**2)))

    return {
        "E_ms": e_total,
        "HS_ms": rmse_hs,
        "TO_ms": rmse_to,
        "Step_ms": rmse_step,
        "Stride_ms": rmse_stride,
    }


def score_layout(
    sensor_xy: np.ndarray,
    dataset: InsoleDataset,
    trials: Optional[Sequence[TrialData]] = None,
    include_overlap_penalty: bool = False,
    aggregation: str = DEFAULT_AGGREGATION,
) -> float:
    """
    Main objective entry point for MOPSO, PSO, and SLSQP in optimize.py.
    Returns mean E(X) (ms) over target trials. Constraints are enforced as hard
    constraints by the optimizers, so the overlap penalty is off by default.
    `aggregation` selects how sensors are combined ("sum" or "first_last").
    """
    sensor_xy = np.asarray(sensor_xy, dtype=np.float64).reshape(-1, 2)
    target_trials = trials if trials is not None else dataset.trials
    if not target_trials:
        raise ValueError("No trials provided to score_layout().")

    e_vals = [score_trial(sensor_xy, tr, dataset, aggregation)["E_ms"] for tr in target_trials]
    total = float(np.mean(e_vals))
    if include_overlap_penalty:
        total += overlap_penalty(sensor_xy, sensor_radius_cm=dataset.sensor_radius_cm)
    return total



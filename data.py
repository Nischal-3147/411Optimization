def load_gaitrite(csv_path: str | Path) -> GroundTruth:
    """Read a GAITRite semicolon-delimited CSV (handles multiline Yarray cells)."""
    df = pd.read_csv(csv_path, sep=";")
    if df.empty:
        raise ValueError(f"Empty GAITRite file: {csv_path}")

    df = df.sort_values("FirstContact").reset_index(drop=True)
    return GroundTruth(
        pt_code=str(df["PT_Code"].iloc[0]) if "PT_Code" in df.columns else "",
        gait_id=int(df["Gait_Id"].iloc[0]) if "Gait_Id" in df.columns else -1,
        foot=df["Foot"].to_numpy(dtype=np.int32),
        first_contact=df["FirstContact"].to_numpy(dtype=np.float64),
        last_contact=df["LastContact"].to_numpy(dtype=np.float64),
        step_time=df["Step_time"].fillna(0.0).to_numpy(dtype=np.float64),
        stride_time=df["Stride_time"].fillna(0.0).to_numpy(dtype=np.float64),
    )


def load_insole_csv(
    csv_path: str | Path, offset_seconds: float
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Load L.csv or R.csv, align timestamps to the GAITRite clock, and remove
    per-sensor unloaded ADC offset (~32 counts).
    """
    df = pd.read_csv(csv_path)
    p_cols = [f"PressureSensor {i}" for i in range(NUM_REAL_SENSORS)]
    P = df[p_cols].to_numpy(dtype=np.float32)

    baseline = np.percentile(P, 5, axis=0, keepdims=True).astype(np.float32)
    P_zeroed = np.maximum(0.0, P - baseline)

    # Verified against sync_auto.json: t_gr = frame / 64.0 - offset_seconds
    t_aligned = np.arange(len(df), dtype=np.float64) / FS_HZ - float(offset_seconds)
    return t_aligned, P_zeroed



_BEZIER_RE = re.compile(
    r"([mM])\s*([-\d.eE]+),([-\d.eE]+)\s*([cC])\s*"
    r"([-\d.eE]+),([-\d.eE]+)\s+([-\d.eE]+),([-\d.eE]+)\s+([-\d.eE]+),([-\d.eE]+)"
)
_MIRROR_RE = re.compile(
    r"matrix\(\s*-1\s*,\s*0\s*,\s*0\s*,\s*1\s*,\s*([-\d.eE]+)\s*,\s*0\s*\)"
)


def _sample_cubic_bezier(
    p0: np.ndarray, p1: np.ndarray, p2: np.ndarray, p3: np.ndarray, n: int = 25
) -> np.ndarray:
    """Evaluate a cubic Bezier segment at n evenly spaced parameter values."""
    t = np.linspace(0.0, 1.0, n)[:, None]
    return (
        ((1.0 - t) ** 3) * p0
        + 3.0 * ((1.0 - t) ** 2) * t * p1
        + 3.0 * (1.0 - t) * (t ** 2) * p2
        + (t ** 3) * p3
    )


def parse_sensors_svg(
    svg_path: str | Path,
    mirror_x: bool = False,
) -> Tuple[np.ndarray, np.ndarray, float, float, float]:
    """
    Parse sensors_map_left.svg or sensors_map_right.svg exported from Inkscape/DXF.
    Returns (xy_cm, outline_cm, width_cm, length_cm, radius_cm) in canonical cm:
      - x in [0, width_cm]  (lateral -> medial on Left; mirrored for Right)
      - y in [0, length_cm] (0 = heel, length_cm = toe)
    """
    tree = ET.parse(svg_path)
    root = tree.getroot()

    mirror_x_offset: Optional[float] = None
    geom_parent: Optional[ET.Element] = None
    for elem in root.iter():
        if elem.tag.split("}")[-1] == "g":
            if "transform" in elem.attrib:
                m = _MIRROR_RE.search(elem.attrib["transform"])
                if m:
                    mirror_x_offset = float(m.group(1))
            if sum(1 for c in elem if c.tag.split("}")[-1] == "path") > 100:
                geom_parent = elem

    if geom_parent is None:
        raise ValueError(f"Could not locate geometry <g> layer in {svg_path}.")

    circles: List[Tuple[float, float, float]] = []
    outline_segs: List[np.ndarray] = []
    r_px_exact = 31.74799  # Exact pad radius in 96-DPI CAD paths (8.400 mm)

    for elem in geom_parent:
        if elem.tag.split("}")[-1] != "path":
            continue
        pid_m = re.search(r"(\d+)", elem.attrib.get("id", "0"))
        pid = int(pid_m.group(1)) if pid_m else 0
        m = _BEZIER_RE.match(elem.attrib.get("d", "").strip())
        if not m:
            continue

        x0, y0 = float(m.group(2)), float(m.group(3))
        c_cmd = m.group(4)
        vals = [float(m.group(i)) for i in range(5, 11)]

        if pid < 390:
            # Top-dead-center arc of each 5- or 6-arc circle has dy1 == 0
            if (
                c_cmd == "c"
                and abs(vals[1]) < 1e-3
                and (abs(vals[0] + 12.84086) < 0.1 or abs(vals[0] + 17.53393) < 0.1)
            ):
                cx = (mirror_x_offset - x0) if mirror_x_offset is not None else x0
                cy = y0 + r_px_exact
                circles.append((cx, cy, r_px_exact))
        else:
            p0 = np.array([x0, y0], dtype=np.float64)
            if c_cmd == "c":
                p1 = p0 + np.array(vals[0:2])
                p2 = p0 + np.array(vals[2:4])
                p3 = p0 + np.array(vals[4:6])
            else:
                p1 = np.array(vals[0:2])
                p2 = np.array(vals[2:4])
                p3 = np.array(vals[4:6])
            seg = _sample_cubic_bezier(p0, p1, p2, p3, n=25)
            if mirror_x_offset is not None:
                seg[:, 0] = mirror_x_offset - seg[:, 0]
            outline_segs.append(seg)

    circles_arr = np.asarray(circles, dtype=np.float64)
    outline_px = np.vstack(outline_segs)

    # Extract numeric <text> labels 0..31 (skips stray empty <text> tags)
    labels: List[Tuple[int, float, float]] = []
    for elem in root.iter():
        if elem.tag.split("}")[-1] == "text":
            txt = "".join(elem.itertext()).strip()
            if txt.isdigit():
                labels.append((int(txt), float(elem.attrib["x"]), float(elem.attrib["y"])))

    if len(circles_arr) != NUM_REAL_SENSORS or len(labels) != NUM_REAL_SENSORS:
        raise ValueError(
            f"{svg_path}: expected {NUM_REAL_SENSORS} circles & labels, "
            f"found {len(circles_arr)} circles and {len(labels)} labels."
        )

    # Match each numbered label to its enclosing circle center
    xy_px = np.zeros((NUM_REAL_SENSORS, 2), dtype=np.float64)
    used = set()
    for sensor_idx, tx, ty in labels:
        dists = np.hypot(circles_arr[:, 0] - (tx + 12.0), circles_arr[:, 1] - (ty - 12.0))
        best = int(np.argmin(dists))
        if best in used:
            raise ValueError(f"{svg_path}: duplicate circle match for sensor {sensor_idx}.")
        used.add(best)
        xy_px[sensor_idx] = circles_arr[best, :2]

    # Shift to insole outline origin and convert px -> cm (flip y: 0 = heel)
    x_min, x_max = float(outline_px[:, 0].min()), float(outline_px[:, 0].max())
    y_min, y_max = float(outline_px[:, 1].min()), float(outline_px[:, 1].max())
    width_cm = (x_max - x_min) / PX_PER_CM
    length_cm = (y_max - y_min) / PX_PER_CM
    radius_cm = float(np.mean(circles_arr[:, 2])) / PX_PER_CM

    xy_cm = np.column_stack([
        (xy_px[:, 0] - x_min) / PX_PER_CM,
        (y_max - xy_px[:, 1]) / PX_PER_CM,
    ])
    outline_cm = np.column_stack([
        (outline_px[:, 0] - x_min) / PX_PER_CM,
        (y_max - outline_px[:, 1]) / PX_PER_CM,
    ])

    if mirror_x:
        xy_cm[:, 0] = width_cm - xy_cm[:, 0]
        outline_cm[:, 0] = width_cm - outline_cm[:, 0]

    return xy_cm, outline_cm, width_cm, length_cm, radius_cm



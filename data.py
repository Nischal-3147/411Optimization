@dataclass
class GroundTruth:
    """GAITRite ground-truth contact events and temporal metrics (seconds)."""
    pt_code: str
    gait_id: int
    foot: np.ndarray            # 0 = Left, 1 = Right, shape (M,)
    first_contact: np.ndarray   # Heel-strike times (s), shape (M,)
    last_contact: np.ndarray    # Toe-off times (s), shape (M,)
    step_time: np.ndarray       # GAITRite Step_time (s), 0.0 if undefined
    stride_time: np.ndarray     # GAITRite Stride_time (s), 0.0 if undefined


@dataclass
class TrialData:
    """Preprocessed single walking trial ready for fast optimizer scoring."""
    trial_id: str
    patient_id: str             # "P1" .. "P24" (excluding P18, P22)
    pace: str                   # "NP", "SP", or "FP"
    t_left: np.ndarray          # Aligned timestamps (s), shape (T_L,)
    t_right: np.ndarray         # Aligned timestamps (s), shape (T_R,)
    raw_left: np.ndarray       # Baseline-subtracted 32-sensor matrix (T_L, 32), float32
    raw_right: np.ndarray       # Baseline-subtracted 32-sensor matrix (T_R, 32), float32
    ground_truth: GroundTruth


@dataclass
class InsoleDataset:
    """Cached multi-patient dataset bundle loaded by optimize.py."""
    gx: np.ndarray              # 1D x-grid coordinates (cm), shape (GRID_NX,)
    gy: np.ndarray              # 1D y-grid coordinates (cm), shape (GRID_NY,)
    width_cm: float             # Exact w (8.933 cm)
    length_cm: float            # Exact l (27.540 cm)
    sensor_radius_cm: float     # Exact r (0.840 cm)
    sensor_xy_left: np.ndarray  # Canonical (32, 2) cm coords for Left insole
    sensor_xy_right: np.ndarray # Canonical (32, 2) cm coords (mirrored to Left frame)
    outline_cm: np.ndarray      # Sampled (K, 2) cm contour for plotting
    insole_mask: np.ndarray     # Boolean (GRID_NY, GRID_NX) convex-hull mask
    W_left: np.ndarray          # Interpolation weights (GRID_NY, GRID_NX, 32), float32
    W_right: np.ndarray         # Interpolation weights (GRID_NY, GRID_NX, 32), float32
    trials: List[TrialData]

    @property
    def bounds(self) -> Tuple[Tuple[float, float], Tuple[float, float]]:
        """Box bounds [r, w - r] and [r, l - r] for optimizer clamping."""
        r = self.sensor_radius_cm
        return (r, self.width_cm - r), (r, self.length_cm - r)

    def get_trials_by_pace(self, pace: str) -> List[TrialData]:
        """Return all trials matching a given cadence ('NP', 'SP', or 'FP')."""
        target = pace.upper()
        return [tr for tr in self.trials if tr.pace.upper() == target]

    def mean_pressure_map(self, pace: str = "NP") -> np.ndarray:
        """Compute average 2D pressure map (GRID_NY, GRID_NX) for heatmap plots."""
        subset = self.get_trials_by_pace(pace) or self.trials
        accum = np.zeros((len(self.gy), len(self.gx)), dtype=np.float64)
        total_frames = 0
        for tr in subset:
            accum += np.maximum(tr.raw_left @ self.W_left.reshape(-1, 32).T, 0.0).sum(0).reshape(accum.shape)
            accum += np.maximum(tr.raw_right @ self.W_right.reshape(-1, 32).T, 0.0).sum(0).reshape(accum.shape)
            total_frames += len(tr.raw_left) + len(tr.raw_right)
        return accum / max(1, total_frames)

    def to_cache_dict(self) -> Dict[str, object]:
        """Serialize to plain Python/NumPy primitives so pickle is module-independent."""
        return asdict(self)

    @classmethod
    def from_cache_dict(cls, payload: Dict[str, object]) -> "InsoleDataset":
        """Reconstruct InsoleDataset from cached dictionary."""
        trials = [
            TrialData(
                trial_id=tr["trial_id"],
                patient_id=tr["patient_id"],
                pace=tr["pace"],
                t_left=tr["t_left"],
                t_right=tr["t_right"],
                raw_left=tr["raw_left"],
                raw_right=tr["raw_right"],
                ground_truth=GroundTruth(**tr["ground_truth"]),
            )
            for tr in payload["trials"]
        ]
        return cls(
            gx=payload["gx"],
            gy=payload["gy"],
            width_cm=payload["width_cm"],
            length_cm=payload["length_cm"],
            sensor_radius_cm=payload["sensor_radius_cm"],
            sensor_xy_left=payload["sensor_xy_left"],
            sensor_xy_right=payload["sensor_xy_right"],
            outline_cm=payload["outline_cm"],
            insole_mask=payload["insole_mask"],
            W_left=payload["W_left"],
            W_right=payload["W_right"],
            trials=trials,
        )



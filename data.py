def discover_trials(
    dataset_dir: str | Path = DATASET_DIR,
    patient_ids: Sequence[str] = PATIENT_IDS,
    paces: Sequence[str] = PACES,
    trials_per_person: int = TRIALS_PER_PERSON,
) -> List[Dict[str, str | Path]]:
    """
    Discover walking trials under:
        411Optimization/insole-gaitrite-dataset/P{i}/{pace}/{1,2,...}/
    Keeps the first `trials_per_person` (numerically sorted) subtrial folders per
    patient & pace that contain L.csv, R.csv, gaitrite_test.csv, and sync_auto.json.
    """
    root = Path(dataset_dir)
    specs: List[Dict[str, str | Path]] = []

    for pid in patient_ids:
        for pace in paces:
            pace_dir = root / pid / pace
            if not pace_dir.is_dir():
                continue

            subfolders = sorted(
                (d for d in pace_dir.iterdir() if d.is_dir() and d.name.isdigit()),
                key=lambda d: int(d.name),
            )
            kept = 0
            for folder in subfolders:
                if kept >= trials_per_person:
                    break
                sub = folder.name
                l_csv = folder / "L.csv"
                r_csv = folder / "R.csv"
                gr_csv = folder / "gaitrite_test.csv"
                sync_file = folder / "sync_auto.json"

                if not (l_csv.exists() and r_csv.exists() and gr_csv.exists() and sync_file.exists()):
                    continue

                specs.append({
                    "trial_id": f"{pid}/{pace}/{sub}",
                    "patient_id": pid,
                    "pace": pace,
                    "L_csv": l_csv,
                    "R_csv": r_csv,
                    "gaitrite_csv": gr_csv,
                    "sync_json": sync_file,
                })
                kept += 1

    if not specs:
        raise FileNotFoundError(
            f"No valid trials found under {root}. Expected "
            "P1..P24/{NP,SP,FP}/{1,2,...}/ containing L.csv, R.csv, "
            "gaitrite_test.csv, and sync_auto.json."
        )
    return specs


def build_dataset(
    dataset_dir: str | Path = DATASET_DIR,
    svg_left: str | Path = SVG_LEFT_PATH,
    svg_right: str | Path = SVG_RIGHT_PATH,
    cache_path: str | Path = CACHE_PATH,
    patient_ids: Sequence[str] = PATIENT_IDS,
    paces: Sequence[str] = PACES,
) -> InsoleDataset:
    """Preprocess all discovered patient trials once and save to cache_path."""
    xy_L, outline_cm, width_cm, length_cm, radius_cm = parse_sensors_svg(svg_left, mirror_x=False)
    xy_R, _, w_R, l_R, _ = parse_sensors_svg(svg_right, mirror_x=True)

    if abs(width_cm - w_R) > 0.05 or abs(length_cm - l_R) > 0.05:
        raise ValueError(
            f"Left/Right SVG mismatch: ({width_cm:.3f}, {length_cm:.3f}) vs ({w_R:.3f}, {l_R:.3f})"
        )

    gx = np.linspace(0.0, width_cm, GRID_NX)
    gy = np.linspace(0.0, length_cm, GRID_NY)

    W_L, mask_L = build_rbf_projection(xy_L, gx, gy)
    W_R, mask_R = build_rbf_projection(xy_R, gx, gy)
    insole_mask = mask_L | mask_R

    trial_specs = discover_trials(dataset_dir, patient_ids=patient_ids, paces=paces)
    trials: List[TrialData] = []
    for spec in trial_specs:
        with open(spec["sync_json"], "r", encoding="utf-8") as f:
            sync = json.load(f)

        t_L, P_L = load_insole_csv(spec["L_csv"], sync["L"]["offset_seconds"])
        t_R, P_R = load_insole_csv(spec["R_csv"], sync["R"]["offset_seconds"])
        gt = load_gaitrite(spec["gaitrite_csv"])

        trials.append(
            TrialData(
                trial_id=str(spec["trial_id"]),
                patient_id=str(spec["patient_id"]),
                pace=str(spec["pace"]),
                t_left=t_L,
                t_right=t_R,
                raw_left=P_L,
                raw_right=P_R,
                ground_truth=gt,
            )
        )

    dataset = InsoleDataset(
        gx=gx,
        gy=gy,
        width_cm=width_cm,
        length_cm=length_cm,
        sensor_radius_cm=radius_cm,
        sensor_xy_left=xy_L,
        sensor_xy_right=xy_R,
        outline_cm=outline_cm,
        insole_mask=insole_mask,
        W_left=W_L,
        W_right=W_R,
        trials=trials,
    )

    cache_path = Path(cache_path)
    with open(cache_path, "wb") as f:
        pickle.dump(dataset.to_cache_dict(), f, protocol=pickle.HIGHEST_PROTOCOL)

    pace_counts = {p: len(dataset.get_trials_by_pace(p)) for p in paces}
    print(
        f"Cached {len(trials)} trial(s) across {len({tr.patient_id for tr in trials})} patient(s) "
        f"{pace_counts} -> {cache_path} ({cache_path.stat().st_size / 1e6:.2f} MB)"
    )
    return dataset


def load_cached_dataset(cache_path: str | Path = CACHE_PATH) -> InsoleDataset:
    """Load preprocessed dataset from disk (builds cache automatically if missing)."""
    cache_path = Path(cache_path)
    if not cache_path.exists():
        return build_dataset(cache_path=cache_path)
    with open(cache_path, "rb") as f:
        payload = pickle.load(f)
    return InsoleDataset.from_cache_dict(payload)


